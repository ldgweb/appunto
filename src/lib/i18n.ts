const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, it };

export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

/** "auto" follows the system locale; anything that is not Italian is English. */
export function resolveLang(preference: string, systemLocale: string): Lang {
  if (preference === 'it' || preference === 'en') return preference;
  return systemLocale.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function translator(lang: Lang): Translate {
  const messages = MESSAGES[lang];
  return (key, values) => {
    const template = messages[key] ?? en[key];
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
  };
}
